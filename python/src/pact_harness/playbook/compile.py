"""Extract and rewrite PACT's artifacts for one platform.

Two rewrites do most of the work.

Plugin-relative references become absolute. A persona says
Read(file_path="../protocols/pact-variety.md"), and a command shells out to
python3 -I <plugin>/hooks/shared/session_journal.py. Neither survives being
moved out of the plugin tree, but the files still exist on disk, so resolving
them to the vendored tree's real location makes the prose, the Read calls and
the shell calls all work unchanged. The cost is that the generated document is
tied to one installation path -- which it is, because it is built for that
installation.

$ARGUMENTS becomes {arguments}. Claude Code substitutes the former; the harness
substitutes the latter when a command body is delivered, so the platform kit
never has to reimplement Claude's templating.

What is deliberately not rewritten: the prose that mentions ToolSearch. Pulling
a sentence out of a paragraph is how a compiler silently changes meaning, so
the platform notes say plainly that ToolSearch does not exist and that all
tools are already loaded, and the occurrences are counted as warnings.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from ..errors import PactHarnessError
from .model import Command, Persona, Playbook, SkillSummary

#: Commands excluded from every non-Claude platform.
EXCLUDED_COMMANDS = frozenset({"telegram-setup.md"})

#: Plugin-relative prefixes that must become absolute.
_RELATIVE_REF = re.compile(
    r"\.\./((?:protocols|skills|reference|agents|commands)/[A-Za-z0-9_.\-/]+)"
)
_PLUGIN_ROOT_TOKEN = "${CLAUDE_PLUGIN_ROOT}"

_COMMAND_NAME_RE = re.compile(r"^[a-z][a-z0-9_-]*$")

_PLATFORM_NOTES = {
    "dsh": (
        "Platform notes (generated by pact playbook build).\n"
        "- Every path below is absolute and points at the PACT tree vendored for this installation.\n"
        "- ToolSearch does not exist on this platform; all tools are already loaded. Ignore any "
        "instruction to load deferred tools with it.\n"
        "- The task board and messaging tools are native where the host provides them, and are "
        "supplied by this harness under the same names otherwise.\n"
        "- {arguments} is the placeholder for the user's text in a command body."
    )
}


class PlaybookError(PactHarnessError):
    """The artifacts could not be compiled."""


def split_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Split a markdown file into its YAML frontmatter and its body.

    Only the forms PACT's artifacts actually use are supported: scalars, quoted
    scalars, block scalars, lists of strings and simple one-level maps. Anything
    else is left as a scalar string rather than guessed at.
    """
    if not text.startswith("---\n"):
        return {}, text
    closing = text.find("\n---\n", 4)
    if closing == -1:
        return {}, text
    block = text[4:closing]
    body = text[closing + 5 :]
    return _parse_block(block), body


def _parse_block(block: str) -> dict[str, Any]:
    result: dict[str, Any] = {}
    lines = block.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or line[:1] in (" ", "\t"):
            index += 1
            continue
        if ":" not in line:
            index += 1
            continue
        key, _, rest = line.partition(":")
        key = key.strip()
        rest = rest.strip()
        if rest in ("|", ">"):
            index += 1
            chunk: list[str] = []
            while index < len(lines) and (lines[index].startswith("  ") or not lines[index].strip()):
                chunk.append(lines[index][2:] if lines[index].startswith("  ") else "")
                index += 1
            result[key] = "\n".join(chunk).strip("\n")
            continue
        if rest == "":
            index += 1
            items: list[str] = []
            mapping: dict[str, str] = {}
            while index < len(lines) and (lines[index].startswith("  ") or not lines[index].strip()):
                nested = lines[index].strip()
                if nested.startswith("- "):
                    items.append(nested[2:].strip().strip('"'))
                elif nested and not nested.startswith("#") and ":" in nested:
                    sub_key, _, sub_value = nested.partition(":")
                    mapping[sub_key.strip()] = sub_value.strip().strip('"')
                index += 1
            result[key] = items if items else mapping
            continue
        if len(rest) >= 2 and rest[0] == rest[-1] and rest[0] in ("'", '"'):
            rest = rest[1:-1]
        result[key] = rest
        index += 1
    return result


def rewrite_text(text: str, plugin_root: Path) -> tuple[str, dict[str, int]]:
    """Apply the path and placeholder rewrites, returning counts."""
    root = str(plugin_root)
    stats = {"arguments": 0, "relative_refs": 0, "plugin_root_tokens": 0, "toolsearch": 0}
    stats["arguments"] = text.count("$ARGUMENTS")
    rewritten = text.replace("$ARGUMENTS", "{arguments}")
    stats["toolsearch"] = rewritten.count("ToolSearch")
    stats["plugin_root_tokens"] = rewritten.count(_PLUGIN_ROOT_TOKEN)
    rewritten = rewritten.replace(_PLUGIN_ROOT_TOKEN, root)

    def substitute(match: re.Match[str]) -> str:
        stats["relative_refs"] += 1
        return f"{root}/{match.group(1)}"

    rewritten = _RELATIVE_REF.sub(substitute, rewritten)
    return rewritten, stats


def _command_name(stem: str) -> str:
    name = f"pact-{stem.lower()}"
    if not _COMMAND_NAME_RE.match(name):
        raise PlaybookError(f"command name {name!r} is not a valid platform command name")
    return name


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise PlaybookError(f"cannot read {path}: {exc}") from exc


def compile_playbook(
    plugin_root: Path,
    *,
    platform: str = "dsh",
    pact_version: str = "",
    commit: str = "",
) -> Playbook:
    """Compile the vendored tree for one platform."""
    root = plugin_root.resolve()
    warnings: list[str] = []
    totals = {"arguments": 0, "relative_refs": 0, "plugin_root_tokens": 0, "toolsearch": 0, "python_calls": 0}

    personas: list[Persona] = []
    for path in sorted((root / "agents").glob("*.md")):
        front, body = split_frontmatter(_read(path))
        name = str(front.get("name") or path.stem)
        rewritten, stats = rewrite_text(body, root)
        for key, value in stats.items():
            totals[key] += value
        metadata = {key: value for key, value in front.items() if key not in ("name", "description")}
        personas.append(
            Persona(
                name=name,
                description=str(front.get("description", "")).strip(),
                body=rewritten,
                source=f"agents/{path.name}",
                metadata=metadata,
            )
        )
    if not personas:
        raise PlaybookError(f"no agent personas found under {root / 'agents'}")

    commands: list[Command] = []
    for path in sorted((root / "commands").glob("*.md")):
        if path.name in EXCLUDED_COMMANDS:
            warnings.append(f"excluded commands/{path.name}: not applicable off Claude Code")
            continue
        front, body = split_frontmatter(_read(path))
        rewritten, stats = rewrite_text(body, root)
        for key, value in stats.items():
            totals[key] += value
        totals["python_calls"] += rewritten.count("python3 ")
        commands.append(
            Command(
                name=_command_name(path.stem),
                description=str(front.get("description", "")).strip(),
                argument_hint=str(front.get("argument-hint", "")).strip(),
                body=rewritten,
                source=f"commands/{path.name}",
            )
        )

    skills: list[SkillSummary] = []
    for path in sorted((root / "skills").glob("*/SKILL.md")):
        front, _ = split_frontmatter(_read(path))
        name = str(front.get("name") or path.parent.name)
        skills.append(
            SkillSummary(
                name=name,
                description=str(front.get("description", "")).strip(),
                path=str(path.parent),
                source=f"skills/{path.parent.name}/SKILL.md",
            )
        )

    protocols = tuple(sorted(path.stem for path in (root / "protocols").glob("*.md")))
    references = tuple(sorted(path.stem for path in (root / "reference").glob("*.md")))

    if totals["toolsearch"]:
        warnings.append(
            f"{totals['toolsearch']} ToolSearch mention(s) left in prose; the platform notes "
            "state that ToolSearch does not exist here"
        )
    if totals["python_calls"]:
        warnings.append(
            f"{totals['python_calls']} direct python3 invocation(s) remain; their paths are "
            "absolute, so they run, but harness verbs are preferable"
        )

    return Playbook(
        platform=platform,
        pact_version=pact_version,
        commit=commit,
        plugin_root=str(root),
        personas=tuple(personas),
        commands=tuple(commands),
        skills=tuple(skills),
        protocols=protocols,
        references=references,
        platform_notes=_PLATFORM_NOTES.get(platform, ""),
        warnings=tuple(warnings),
    )
